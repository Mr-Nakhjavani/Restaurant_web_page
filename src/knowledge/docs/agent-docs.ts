export function scenariosDoc(k: KnowledgeContext): string {
  const scenarios = buildScenarios(k);
  const out = [
    header(k, "agent-test-scenarios", "Voice-Agent Test Scenarios", "Unusual, adversarial and boundary questions with the expected handling. These are test cases for evaluating the external agent, not FAQ answers. Machine-readable copy: docs/restaurant-knowledge/agent-test-scenarios.json and GET /api/v1/knowledge/scenarios."),
    "Each scenario lists the correct handling, whether clarification is needed, which API calls are expected, what must never be promised, and when to reject or escalate.",
    "",
    table(["#", "Scenario", "Expected outcome"], scenarios.map((s) => [s.id, s.title, s.expectedOutcome.join(", ")])),
    "",
  ];
  for (const s of scenarios) {
    out.push(
      `## ${s.id}: ${s.title}`,
      "",
      `> “${s.customerSays}”`,
      "",
      `- **Category:** ${s.category}`,
      `- **Expected outcome:** ${s.expectedOutcome.join(", ")}`,
      `- **Correct handling:** ${s.correctHandling}`,
      `- **Clarification needed:** ${s.clarificationNeeded ?? "No"}`,
      `- **API calls:** ${s.apiCalls.length ? s.apiCalls.map((a) => `\`${a}\``).join("; ") : "none required"}`,
      `- **Must not promise:** ${s.mustNotPromise.length ? s.mustNotPromise.join("; ") : "—"}`,
      `- **Reject / escalate when:** ${s.rejectOrEscalateWhen}`,
      `- **Expected error codes:** ${s.expectedErrorCodes.length ? s.expectedErrorCodes.join("; ") : "—"}`,
      "",
    );
  }
  return out.join("\n");
}

