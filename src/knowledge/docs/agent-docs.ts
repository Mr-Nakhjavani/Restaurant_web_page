export function faqDoc(k: KnowledgeContext): string {
  const faq = buildFaq(k);
  const out = [header(k, "faq", "Frequently Asked Questions", "Customer-friendly answers to common questions, grouped by topic. Also available as structured data at GET /api/v1/faq.")];
  out.push("## Contents", "", ...FAQ_CATEGORIES.map((c) => `- ${c} (${faq.filter((f) => f.category === c).length})`), "");
  for (const c of FAQ_CATEGORIES) {
    out.push(`## ${c}`, "");
    for (const f of faq.filter((x) => x.category === c)) {
      out.push(`### ${f.question}`, "", f.answer, "", `<sub>id: ${f.id} · see: ${f.relatedDocuments.join(", ")}</sub>`, "");
    }
  }
  return out.join("\n");
}

