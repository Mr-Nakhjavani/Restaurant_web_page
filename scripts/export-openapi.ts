/**
 * Writes the generated API documentation:
 *   docs/api/openapi.json   — OpenAPI 3.1 from the live route definitions
 *   docs/api/api-reference.md — endpoint index (method, path, auth, summary)
 *   docs/api/error-codes.md — the machine-readable error catalogue
 * The server URL is a placeholder; deployments serve their own copy at /api/v1/openapi.json.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { generateOpenApi } from "@/server/api/openapi-doc";
import { ERROR_CATALOG } from "@/server/errors";

const dir = path.join(process.cwd(), "docs", "api");
mkdirSync(dir, { recursive: true });
const doc = generateOpenApi("http://localhost:3000");
writeFileSync(path.join(dir, "openapi.json"), JSON.stringify(doc, null, 2) + "\n");

type Op = { summary?: string; tags?: string[]; security?: Record<string, string[]>[]; description?: string };
const authOf = (op: Op) => {
  const s = op.security;
  if (!s || s.length === 0) return "public";
  const names = s.flatMap((r) => Object.keys(r));
  if (names.includes("AdminSession")) return "staff/admin key or session";
  if (names.includes("CustomerPhone")) return "verification (phone or token) or staff key";
  if (s.some((r) => Object.keys(r).length === 0)) return "public (API key optional)";
  return names.join(", ");
};
const rows: string[] = [];
const byTag = new Map<string, string[]>();
for (const [p, methods] of Object.entries(doc.paths ?? {})) {
  for (const [m, op] of Object.entries(methods as Record<string, Op>)) {
    const tag = op.tags?.[0] ?? "Other";
    const line = `| \`${m.toUpperCase()}\` | \`/api/v1${p}\` | ${authOf(op)} | ${op.summary ?? ""} |`;
    byTag.set(tag, [...(byTag.get(tag) ?? []), line]);
  }
}
for (const [tag, lines] of byTag) rows.push(`## ${tag}`, "", "| Method | Path | Access | Summary |", "| --- | --- | --- | --- |", ...lines, "");
writeFileSync(
  path.join(dir, "api-reference.md"),
  [
    "# API reference (endpoint index)",
    "",
    "> Generated by `npm run openapi:export` from the same route definitions that validate requests. Full schemas, parameters and examples: [`openapi.json`](./openapi.json) (also served live at `/api/v1/openapi.json`, with Swagger UI at `/api/v1/docs`). Worked request/response examples: [`examples.md`](./examples.md). Error codes: [`error-codes.md`](./error-codes.md).",
    "",
    "Conventions:",
    "",
    "- Base path `/api/v1`. JSON in and out (`Content-Type: application/json`), UTF-8.",
    "- Success: `{ \"data\": … , \"meta\"?: … }`. Error: `{ \"error\": { code, message, status, category, retryable, requestId, details? } }`.",
    "- Local dates `YYYY-MM-DD` and times `HH:mm` are Dubai time (UTC+04:00); timestamps are ISO-8601 with offset.",
    "- Money: `{ amountFils, amount, currency: \"AED\", formatted }` — prices include 5% VAT.",
    "- `Authorization: Bearer <api key>` identifies an external client (scopes: `agent`, `staff`, `admin`).",
    "- Customer records need `X-Customer-Phone` (the number used) or `X-Access-Token` (returned at creation) unless the caller is staff.",
    "- POST create endpoints accept `Idempotency-Key` (8–128 chars).",
    "- Every response carries `X-Request-Id`; rate-limited responses carry `RateLimit-*` and `Retry-After`.",
    "",
    `Total: ${Object.values(doc.paths ?? {}).reduce((n, m) => n + Object.keys(m as object).length, 0)} operations on ${Object.keys(doc.paths ?? {}).length} paths, plus \`GET /api/health\`.`,
    "",
    ...rows,
  ].join("\n"),
);

const errRows = Object.entries(ERROR_CATALOG).map(([code, e]) => `| \`${code}\` | ${e.status} | ${e.category} | ${e.retryable ? "yes" : "no"} | ${e.description} | ${e.agentGuidance} |`);
writeFileSync(
  path.join(dir, "error-codes.md"),
  [
    "# Error codes",
    "",
    "> Generated from `src/server/errors.ts`. Branch on `error.code`; never on the message text.",
    "",
    "```json",
    JSON.stringify(
      {
        error: {
          code: "ITEM_UNAVAILABLE",
          message: "Friday Family Machboos Platter is only available on Fridays; Tuesday 27 October 2026 is a Tuesday.",
          status: 422,
          category: "unavailable_item",
          retryable: false,
          requestId: "req_2kV3m0x9QeHf",
          details: { issues: ["…"], items: [{ itemId: "mi_friday_platter", reasons: ["NOT_AVAILABLE_ON_DAY"], nextAvailable: { date: "2026-10-30", time: "12:00" }, alternatives: ["…"] }] },
        },
      },
      null,
      2,
    ),
    "```",
    "",
    "How to tell problems apart:",
    "",
    "- **Invalid request** (fix the request or ask the customer): `400 VALIDATION_ERROR`, `INVALID_JSON`, `422` validation-category codes such as `INVALID_PHONE`, `INVALID_QUANTITY`.",
    "- **Unavailable item** (offer `nextAvailable` / `alternatives`): `422 ITEM_UNAVAILABLE` (category `unavailable_item`).",
    "- **Business rule** (explain and offer alternatives): `422` with category `business_rule`.",
    "- **Conflict** (someone else took the slot/table, duplicate, wrong state): `409`.",
    "- **Server failure** (nothing happened; retry once, then apologise): `500 INTERNAL_ERROR`, `503 SERVICE_UNAVAILABLE` — `retryable: true`.",
    "",
    "| Code | HTTP | Category | Retryable | Meaning | What an agent should do |",
    "| --- | --- | --- | --- | --- | --- |",
    ...errRows,
    "",
    "Availability reason codes (inside `availability.reasons[]` and `details.items[].reasons`): `ITEM_PAUSED`, `ITEM_SOLD_OUT`, `DAILY_LIMIT_REACHED`, `NOT_AVAILABLE_ON_DAY`, `OUTSIDE_ITEM_HOURS`, `OUTSIDE_DATE_RANGE`, `OUTSIDE_SPECIAL_PERIOD`, `NOT_DURING_SPECIAL_PERIOD`, `FULFILMENT_NOT_SUPPORTED`, `INSUFFICIENT_NOTICE`, `SAME_DAY_CUTOFF_PASSED`, `PREORDERS_NOT_OPEN`, `BELOW_MINIMUM_QUANTITY`, `CHANNEL_NOT_ALLOWED`, `BULK_ONLY_ITEM`, `RESTAURANT_CLOSED`, `IN_THE_PAST`.",
    "",
    "Catering quote issue codes (inside `issues[]`, each with `blocking`): `BULK_ORDERS_PAUSED`, `ITEM_NOT_BULK_ELIGIBLE`, `BELOW_ITEM_MINIMUM`, `ITEM_DAILY_MAXIMUM_EXCEEDED`, `EXCEEDS_MAX_BULK_PORTIONS`, `INSUFFICIENT_NOTICE`, `DAILY_CAPACITY_EXCEEDED`, `OUTSIDE_FULFILMENT_HOURS`, `RESTAURANT_CLOSED`, `TOO_FAR_IN_ADVANCE`, `DATE_IN_PAST`, `ITEM_UNAVAILABLE_ON_DATE`, `DELIVERY_ADDRESS_REQUIRED`, `DELIVERY_AREA_NOT_SERVED`, `BELOW_DELIVERY_MINIMUM`, plus line validation codes.",
    "",
  ].join("\n"),
);
console.log(`wrote docs/api/openapi.json (${Object.keys(doc.paths ?? {}).length} paths), api-reference.md, error-codes.md`);
