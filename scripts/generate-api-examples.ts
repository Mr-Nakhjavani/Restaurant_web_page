/**
 * Generates docs/api/examples.md by calling the real API in-process against a freshly
 * reset *_test database with a fixed clock (Monday 26 October 2026, 10:00 Dubai).
 * Every response shown in the document is a genuine response (long arrays are trimmed).
 *
 *   DATABASE_URL=postgresql://…/bayt_al_ghaf_test ENABLE_TEST_CLOCK=true npx tsx scripts/generate-api-examples.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

process.env.ENABLE_TEST_CLOCK = "true";
process.env.RATE_LIMIT_ENABLED = "false";
process.env.SIMULATE_KITCHEN_PROGRESS = "false";
process.env.SEED_AGENT_API_KEY ??= "bg_test_agent_key_0123456789";
process.env.SEED_ADMIN_EMAIL ??= "admin@baytalghaf.example";
process.env.SEED_ADMIN_PASSWORD ??= "Example-Admin-Password-1";

const NOW = "2026-10-26T10:00:00+04:00";
const KEY = process.env.SEED_AGENT_API_KEY;

function trim(value: unknown, depth = 0): unknown {
  if (Array.isArray(value)) {
    const limit = depth === 0 ? 3 : 2;
    const head = value.slice(0, limit).map((v) => trim(v, depth + 1));
    return value.length > limit ? [...head, `… ${value.length - limit} more`] : head;
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, trim(v, depth + 1)]));
  }
  if (typeof value === "string" && value.length > 400) return value.slice(0, 400) + "…";
  return value;
}

async function main() {
  const db = new URL(process.env.DATABASE_URL ?? "").pathname.slice(1);
  if (!db.endsWith("_test")) throw new Error("Run against a *_test database (it is reset).");
  const { resetDatabase } = await import("../tests/integration/db-reset");
  await resetDatabase();
  const { createApp } = await import("@/server/api/app");
  const app = createApp();
  const out: string[] = [
    "# API examples",
    "",
    "> Generated by `scripts/generate-api-examples.ts`: every response below is a real response from the API, captured against a freshly seeded test database with the clock fixed to **Monday 26 October 2026, 10:00 Dubai time** (`X-Test-Now`, available only when `ENABLE_TEST_CLOCK=true`). Long arrays are trimmed (`… N more`). Request IDs, references and tokens will differ on your system.",
    "",
    "Base URL in the examples: `http://localhost:3000/api/v1`. `$KEY` is an API key with scope `agent`.",
    "",
  ];
  const state: Record<string, string> = {};
  async function ex(title: string, method: string, url: string, opts: { body?: unknown; headers?: Record<string, string>; note?: string; keep?: (b: any) => void } = {}) { // eslint-disable-line @typescript-eslint/no-explicit-any
    const headers: Record<string, string> = { "x-test-now": NOW, ...(opts.body ? { "content-type": "application/json" } : {}), ...(opts.headers ?? {}) };
    const res = await app.request(`/api/v1${url}`, { method, headers, body: opts.body ? JSON.stringify(opts.body) : undefined });
    const text = await res.text();
    let body: unknown = text;
    try {
      body = JSON.parse(text);
    } catch {
      body = text.slice(0, 600) + (text.length > 600 ? "\n…" : "");
    }
    opts.keep?.(body);
    const shownHeaders = Object.entries(opts.headers ?? {})
      .map(([k, v]) => (k === "authorization" ? ` \\\n  -H "Authorization: Bearer $KEY"` : ` \\\n  -H '${k.replace(/(^|-)([a-z])/g, (_m, p, c) => p + c.toUpperCase())}: ${v}'`))
      .join("");
    out.push(`## ${title}`, "");
    if (opts.note) out.push(opts.note, "");
    out.push(
      "```bash",
      `curl -s -X ${method} 'http://localhost:3000/api/v1${url}'${opts.body ? " \\\n  -H 'Content-Type: application/json'" : ""}${shownHeaders}${opts.body ? ` \\\n  -d '${JSON.stringify(opts.body)}'` : ""}`,
      "```",
      "",
      `Response \`${res.status}\`:`,
      "",
      typeof body === "string" ? "```markdown" : "```json",
      typeof body === "string" ? body : JSON.stringify(trim(body), null, 2),
      "```",
      "",
    );
  }
  const auth = { authorization: `Bearer ${KEY}` };

  out.push("# 1. Restaurant information", "");
  await ex("Health", "GET", "/health");
  await ex("Opening hours today and tomorrow", "GET", "/restaurant/hours?days=2");
  await ex("Delivery area check", "GET", "/delivery/check?area=Karama");

  out.push("# 2. Menu, ingredients and availability", "");
  await ex("Find a dish from a description", "GET", "/menu/search?q=rice%20meat%20dried%20lemon&limit=2");
  await ex("Dish details with ingredients and allergens", "GET", "/menu/items/lamb-machboos");
  await ex("What exactly is in a house sauce", "GET", "/sauces/sauce-no-7");
  await ex("Is the Friday platter available on Tuesday?", "GET", "/menu/items/mi_friday_platter/availability?date=2026-10-27&mode=pickup");
  await ex("Vegan dishes without sesame", "GET", "/menu?dietary=vegan&excludeAllergens=sesame&mode=pickup");
  await ex("Cheapest way to feed 15 people", "GET", "/menu/feeding-suggestions?guests=15&date=2026-10-27");

  out.push("# 3. Reservations", "");
  await ex("Check availability for 6 at 19:30 tomorrow", "GET", "/reservations/availability?date=2026-10-27&partySize=6&time=19:30&seatingPreference=terrace");
  await ex("Book the table", "POST", "/reservations", {
    headers: { ...auth, "idempotency-key": "example-res-0001" },
    body: { date: "2026-10-27", time: "19:30", partySize: 6, seatingPreference: "terrace", customer: { name: "Mariam Al Suwaidi", phone: "050 123 4567" }, occasion: "birthday" },
    keep: (b) => (state.res = b.data.reservation.reference),
  });
  await ex("Retrieve it (verification with the caller's phone)", "GET", `/reservations/${state.res}`, { headers: { ...auth, "x-customer-phone": "+971501234567" } });
  await ex("Move it to 20:00", "PATCH", `/reservations/${state.res}`, { headers: { ...auth, "x-customer-phone": "050 123 4567" }, body: { time: "20:00" } });
  await ex("Cancel it", "POST", `/reservations/${state.res}/cancel`, { headers: { ...auth, "x-customer-phone": "050 123 4567" }, body: { reason: "Plans changed" } });

  out.push("# 4. Pickup orders", "");
  await ex("Quote an order (price, availability, earliest time)", "POST", "/orders/quote", {
    body: { items: [{ itemId: "mi_lamb_machboos", quantity: 2, options: ["hashu_no_raisins"] }, { itemId: "mi_karak", quantity: 2 }], fulfilment: { type: "pickup", date: "2026-10-26", time: "13:00" } },
  });
  await ex("Place the pickup order", "POST", "/orders", {
    headers: { ...auth, "idempotency-key": "example-order-0001" },
    body: {
      items: [{ itemId: "mi_lamb_machboos", quantity: 2, options: ["hashu_no_raisins"] }, { itemId: "mi_karak", quantity: 2 }],
      fulfilment: { type: "pickup", date: "2026-10-26", time: "13:00" },
      customer: { name: "Omar Haddad", phone: "058 221 0045" },
    },
    keep: (b) => (state.order = b.data.order.number),
  });
  await ex("Order status", "GET", `/orders/${state.order}/status`, { headers: { ...auth, "x-customer-phone": "058 221 0045" } });

  out.push("# 5. Catering", "");
  await ex("Quote 40 office lunch boxes", "POST", "/bulk-orders/quotes", {
    body: { items: [{ itemId: "mi_office_lunch_box", quantity: 30 }, { itemId: "mi_office_lunch_box", quantity: 10, options: ["main_vegetable"] }], fulfilment: { type: "delivery", date: "2026-10-28", time: "12:30" }, deliveryArea: "Business Bay", guestCount: 40, eventType: "office_lunch" },
    keep: (b) => (state.quote = b.data.quoteId),
  });
  await ex("Place the catering order (always pending until the team confirms)", "POST", "/bulk-orders", {
    headers: { ...auth, "idempotency-key": "example-cat-0001" },
    body: { quoteId: state.quote, customer: { name: "Priya Menon", phone: "052 761 4402" }, companyName: "Creekside Consulting", deliveryAddress: { area: "Business Bay", building: "Bay Square 7", street: "Bay Square", unit: "Office 402" } },
  });
  await ex("An impossible request: 200 machboos in 20 minutes", "POST", "/bulk-orders/quotes", {
    body: { items: [{ itemId: "mi_lamb_machboos", quantity: 200 }], fulfilment: { type: "pickup", date: "2026-10-26", time: "10:30" } },
  });

  out.push("# 6. Unsuccessful requests (what errors look like)", "");
  await ex("Special-day dish on the wrong day", "POST", "/orders", {
    body: { items: [{ itemId: "mi_friday_platter", quantity: 1 }], fulfilment: { type: "pickup", date: "2026-10-27", time: "13:00" }, customer: { name: "Test", phone: "050 555 0100" } },
  });
  await ex("Pickup time the kitchen cannot meet", "POST", "/orders", {
    body: { items: [{ itemId: "mi_hammour_mashwi", quantity: 1 }], fulfilment: { type: "pickup", date: "2026-10-26", time: "10:15" }, customer: { name: "Test", phone: "050 555 0101" } },
  });
  await ex("Delivery outside Dubai", "POST", "/orders/quote", {
    body: { items: [{ itemId: "mi_chicken_machboos", quantity: 2 }], fulfilment: { type: "delivery", date: "2026-10-26", time: "19:00" }, deliveryAddress: { area: "Abu Dhabi", building: "Tower 1", street: "Corniche" } },
    note: "A quote never fails for business reasons — it lists `issues`. The same body sent to `POST /orders` returns `422 DELIVERY_AREA_NOT_SERVED`.",
  });
  await ex("Missing verification", "GET", `/orders/${state.order}`);
  await ex("Validation error", "POST", "/reservations", { body: { date: "2026-10-27", time: "19:30", partySize: 2, customer: { name: "No Phone" } } });

  out.push("# 7. Knowledge base", "");
  await ex("Search the knowledge base", "GET", "/knowledge/search?q=is%20there%20parking&limit=2");
  await ex("FAQ search", "GET", "/faq/search?q=allergic%20to%20sesame%20house%20sauce&limit=1");

  writeFileSync(path.join(process.cwd(), "docs", "api", "examples.md"), out.join("\n"));
  const { prisma } = await import("@/server/db");
  await prisma.$disconnect();
  console.log("wrote docs/api/examples.md");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
